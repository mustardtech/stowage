package sqlstore

import (
	"context"
	"database/sql"
	"strconv"
	"strings"
)

// Dialect selects the SQL flavour a Store speaks. Every query in this
// package is written once, in SQLite's spelling. The DB/Tx wrappers rewrite
// the one mechanical difference (positional placeholders) at execution
// time, and the two places where the difference is semantic
// (case-insensitive compare and pattern match) ask the dialect.
type Dialect int

const (
	// DialectSQLite is the embedded single-file store (the default).
	DialectSQLite Dialect = iota
	// DialectPostgres is a shared PostgreSQL database, the multi-replica
	// option: any number of stowage processes can open it at once.
	DialectPostgres
)

func (d Dialect) String() string {
	switch d {
	case DialectPostgres:
		return "postgres"
	default:
		return "sqlite"
	}
}

// rewrite converts "?" placeholders to "$1".."$n" for Postgres. SQLite text
// is returned untouched. Question marks never appear inside string
// literals in this package's queries, so a plain scan is enough.
func (d Dialect) rewrite(query string) string {
	if d != DialectPostgres || !strings.Contains(query, "?") {
		return query
	}
	var b strings.Builder
	b.Grow(len(query) + 16)
	n := 0
	for i := 0; i < len(query); i++ {
		if query[i] != '?' {
			b.WriteByte(query[i])
			continue
		}
		n++
		b.WriteByte('$')
		b.WriteString(strconv.Itoa(n))
	}
	return b.String()
}

// like returns the case-insensitive pattern-match operator. SQLite's LIKE
// is case-insensitive for ASCII by default; Postgres needs ILIKE.
func (d Dialect) like() string {
	if d == DialectPostgres {
		return "ILIKE"
	}
	return "LIKE"
}

// nocase returns the collation suffix for a case-insensitive equality on
// users.username / users.email. The Postgres columns are CITEXT, so a
// plain "=" already compares case-insensitively there.
func (d Dialect) nocase() string {
	if d == DialectPostgres {
		return ""
	}
	return " COLLATE NOCASE"
}

// ddl translates the SQLite-spelled migration DDL for Postgres. The
// migrations slice stays the single source of truth; these rules are the
// complete list of spellings it uses that Postgres reads differently.
// CURRENT_TIMESTAMP is mapped to itself first so the TIMESTAMP rule cannot
// match inside it.
func (d Dialect) ddl(sqlText string) string {
	if d != DialectPostgres {
		return sqlText
	}
	return postgresDDL.Replace(sqlText)
}

var postgresDDL = strings.NewReplacer(
	"CURRENT_TIMESTAMP", "CURRENT_TIMESTAMP",
	"TEXT NOT NULL COLLATE NOCASE", "CITEXT NOT NULL",
	"TEXT COLLATE NOCASE", "CITEXT",
	"INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
	// SQLite INTEGER is always 64-bit; Postgres INTEGER is int4, which
	// overflows on byte counts (an 80 GiB quota failed the first real copy).
	"INTEGER", "BIGINT",
	"BLOB", "BYTEA",
	"TIMESTAMP", "TIMESTAMPTZ",
)

// DB wraps *sql.DB so every statement passes through the dialect's
// placeholder rewrite. Everything else (Ping, Close, pool settings) is the
// embedded *sql.DB.
type DB struct {
	*sql.DB
	d Dialect
}

func (db *DB) ExecContext(ctx context.Context, query string, args ...any) (sql.Result, error) {
	return db.DB.ExecContext(ctx, db.d.rewrite(query), args...)
}

func (db *DB) QueryContext(ctx context.Context, query string, args ...any) (*sql.Rows, error) {
	return db.DB.QueryContext(ctx, db.d.rewrite(query), args...)
}

func (db *DB) QueryRowContext(ctx context.Context, query string, args ...any) *sql.Row {
	return db.DB.QueryRowContext(ctx, db.d.rewrite(query), args...)
}

func (db *DB) PrepareContext(ctx context.Context, query string) (*sql.Stmt, error) {
	return db.DB.PrepareContext(ctx, db.d.rewrite(query))
}

// BeginTx starts a transaction whose statements are rewritten the same way.
func (db *DB) BeginTx(ctx context.Context, opts *sql.TxOptions) (*Tx, error) {
	tx, err := db.DB.BeginTx(ctx, opts)
	if err != nil {
		return nil, err
	}
	return &Tx{Tx: tx, d: db.d}, nil
}

// Tx is the transaction counterpart of DB.
type Tx struct {
	*sql.Tx
	d Dialect
}

func (tx *Tx) ExecContext(ctx context.Context, query string, args ...any) (sql.Result, error) {
	return tx.Tx.ExecContext(ctx, tx.d.rewrite(query), args...)
}

func (tx *Tx) QueryContext(ctx context.Context, query string, args ...any) (*sql.Rows, error) {
	return tx.Tx.QueryContext(ctx, tx.d.rewrite(query), args...)
}

func (tx *Tx) QueryRowContext(ctx context.Context, query string, args ...any) *sql.Row {
	return tx.Tx.QueryRowContext(ctx, tx.d.rewrite(query), args...)
}

func (tx *Tx) PrepareContext(ctx context.Context, query string) (*sql.Stmt, error) {
	return tx.Tx.PrepareContext(ctx, tx.d.rewrite(query))
}
